# logical_operators.py for (and)
a = 5
result= a > 3 and a < 15
print("result of ",a, ">", 3,"and", a, "<", 15,"is: ", result)

# logical_operators.py for (or)
b = 5
result2 = b < 5 or b > 23
print("result of ",b, "<", 5,"or", b, ">", 23,"is: ", result2)

# logical_operators.py for (not)
c = 5
result3 = not(c > 3)
print("result of not(",c, ">", 3,") is: ", result3)